<h3>Metaznaki i Kwantyfikatory</h3>
<h4>Metaznaki</h4>
<table>
    <tr>
        <th>Metaznak</th>
        <th>Opis</th>
    </tr>
    <tr>
        <td>|</td>
        <td>Znajduje dowolne dopasowanie ze wzorców oddzielonych znakiem.</td>
    </tr>
    <tr>
        <td>.</td>
        <td>Znajdź dowolny znak.</td>
    </tr>
    <tr>
        <td>^</td>
        <td>Znajduje dopasowanie na początku ciągu.</td>
    </tr>
    <tr>
        <td>$</td>
        <td>Znajduje dopasowanie na końcu ciągu.</td>
    </tr>
    <tr>
        <td>\d</td>
        <td>Znajduje dowolne cyfry.</td>
    </tr>
    <tr>
        <td>\D</td>
        <td>Znajduje dowolne znaki niebędące cyframi.</td>
    </tr>
    <tr>
        <td>\s</td>
        <td>Znajduje dowolny znak odstępu.</td>
    </tr>
    <tr>
        <td>\S</td>
        <td>Znajduje dowolny znak niebędący odstępem.</td>
    </tr>
    <tr>
        <td>\w</td>
        <td>Znajduje dowolną literę alfabetu i cyfrę.</td>
    </tr>
    <tr>
        <td>\W</td>
        <td>Znajduje dowolny znak niebędący literą ani cyfrą.</td>
    </tr>
    <tr>
        <td>\b</td>
        <td>Znajduje dopasowanie na początu słowa lub na jego końcu.</td>
    </tr>
    <tr>
        <td>\uxxxx</td>
        <td>Znajduje znak Unicode określony przez liczbę szesnastkową xxxx</td>
    </tr>
</table>
<h4>Kwantyfikatory</h4>
<table>
    <tr>
        <th>Kwantyfikator</th>
        <th>Opis</th>
    </tr>
    <tr>
        <th>n+</th>
        <th>Pasuje do dowolnego ciągu zawierającego co najmniej jedno n.</th>
    </tr>
    <tr>
        <th>n*</th>
        <th>Pasuje do dowolnego ciągu zawierającego zero lub więcej n.</th>
    </tr>
    <tr>
        <th>n?</th>
        <th>Pasuje do dowolnego ciągu zawierającego jedno lub zero n.</th>
    </tr>
    <tr>
        <th>n{3}</th>
        <th>Pasuje do dowolnego ciągu zawierającego sekwencję 3 n.</th>
    </tr>
    <tr>
        <th>n{2, 5}</th>
        <th>Pasuje do dowolnego ciągu zawierającego od 2 do 5 n.</th>
    </tr>
    <tr>
        <th>n{3,}</th>
        <th>pasuje do dowolnego ciągu zawierającego sekwencję co najmniej 3 n.</th>
    </tr>
</table>
