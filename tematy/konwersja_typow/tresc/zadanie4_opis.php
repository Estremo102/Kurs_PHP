<h3>Rzutowanie do Boolean</h3>
Dany jest poniższy kod PHP:
<pre><code class="language-php">&lt;?php
$a = 5;       // Integer
$b = 5.34;    // Float
$c = 0;       // Integer
$d = -1;      // Integer
$e = 0.1;     // Float
$f = "hello"; // String
$g = "";      // String
$h = true;    // Boolean
$i = NULL;    // NULL
?&gt;</code></pre>
<p>Zmienne są już zdefiniowane, nie musisz ich tworzyć.</p>
<p>Zrzutuj dane do typu Boolean i wyświetl wartości zmiennych <code>$a</code>, <code>$b</code>, <code>$c</code>, <code>$d</code>, <code>$e</code>, <code>$f</code>, <code>$g</code>, <code>$h</code> i <code>$i</code> po konwersji do typu Boolean.</p>
<p>Użyj funkcji <code>var_dump()</code>, aby wyświetlić zarówno typ, jak i wartość każdej zmiennej po konwersji. Następnie przeanalizuj wyniki.</p>